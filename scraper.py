Python
import os
import pandas as pd
from datetime import datetime
from playwright.sync_api import sync_playwright

def run_crawling():
    # 스크린샷이 확인된 실제 접속 주소
    url = "https://www.kobis.or.kr/kobis/business/main/main.do"
    filename = 'kobis_reservation_data.csv'
    current_time = datetime.now().strftime('%Y-%m-%d %H:%M:%S')

    with sync_playwright() as p:
        browser = p.chromium.launch(headless=True)
        context = browser.new_context(viewport={'width': 1280, 'height': 800})
        page = context.new_page()
        
        print(f"데이터 수집 페이지 접속 중...")
        page.goto(url, wait_until="networkidle")

        # 스크린샷에 보이는 왼쪽 '예매율' 리스트 영역이 로딩될 때까지 대기
        # 해당 영역은 보통 .ov-all 또는 .mov_list_box 클래스를 사용합니다.
        try:
            page.wait_for_selector(".ov-all", timeout=20000)
        except:
            print("데이터 영역을 찾지 못했습니다. 스크린샷을 다시 찍습니다.")
            page.screenshot(path="debug_screenshot.png")
            browser.close()
            return

        # 스크린샷 왼쪽 리스트의 각 아이템(li)을 가져옵니다.
        items = page.query_selector_all(".ov-all li")
        print(f"분석된 영화 항목: {len(items)}개")
        
        movie_list = []
        for item in items:
            # 제목(strong)과 예매율(span.rate) 추출
            title_el = item.query_selector("strong")
            rate_el = item.query_selector(".rate")
            
            if title_el and rate_el:
                title = title_el.inner_text().strip()
                # '16.3%' 같은 문자열에서 숫자만 추출
                rate = rate_el.inner_text().replace('예매율', '').replace('%', '').strip()
                
                if title:
                    movie_list.append([current_time, title, rate])
                    print(f"✅ 수집: {title} ({rate}%)")

        browser.close()

        if movie_list:
            df = pd.DataFrame(movie_list, columns=['check_time', 'title', 'rate'])
            if os.path.exists(filename):
                df_old = pd.read_csv(filename, encoding='utf-8-sig')
                df = pd.concat([df_old, df], ignore_index=True)
            df.to_csv(filename, index=False, encoding='utf-8-sig')
            print(f"[{current_time}] 데이터 저장 완료!")
        else:
            print("수집된 데이터가 없습니다.")

if __name__ == "__main__":
    run_crawling()
